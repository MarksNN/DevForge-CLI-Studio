export class PersonaRegistry {
  private personas: Map<string, PersonaProfile> = new Map();
  private storagePath: string;

  constructor(customPath?: string) {
    this.storagePath = customPath || path.resolve(process.cwd(), 'data', 'personas_store.json');
    this.init();
  }

  private init(): void {
    // 1. Carrega personas padrão oficiais
    for (const p of OFFICIAL_PERSONAS) {
      this.personas.set(p.agent_id, { ...p });
    }

    // 2. Se houver personalizações salvas em disco pelo usuário, carrega sobrepondo
    try {
      if (fs.existsSync(this.storagePath)) {
        const raw = fs.readFileSync(this.storagePath, 'utf8');
        const customList: PersonaProfile[] = JSON.parse(raw);
        for (const item of customList) {
          const existing = this.personas.get(item.agent_id);
          if (existing) {
            this.personas.set(item.agent_id, {
              ...existing,
              ...item,
              appearance: { ...existing.appearance, ...item.appearance },
              personality: { ...existing.personality, ...item.personality },
              voice: { ...existing.voice, ...item.voice },
            });
          }
        }
      }
    } catch (err) {
      console.warn('[PersonaRegistry] Erro ao carregar personalizações salvas:', err);
    }
  }

  public getPersona(agentId: string): PersonaProfile | undefined {
    return this.personas.get(agentId);
  }

  public getAllPersonas(): PersonaProfile[] {
    return Array.from(this.personas.values());
  }

  public updatePersonaState(agentId: string, state: PersonaState): boolean {
    const p = this.personas.get(agentId);
    if (!p) return false;
    p.state = state;
    return true;
  }

  public customizePersona(agentId: string, updates: Partial<PersonaProfile>): PersonaProfile | null {
    const existing = this.personas.get(agentId);
    if (!existing) return null;

    // Regra Central de Segurança: IDs técnicos e competências oficiais são imutáveis
    const updated: PersonaProfile = {
      ...existing,
      display_name: updates.display_name?.trim() || existing.display_name,
      appearance: {
        ...existing.appearance,
        ...(updates.appearance || {}),
        primaryColor: updates.appearance?.primaryColor || existing.appearance.primaryColor,
      },
      personality: {
        ...existing.personality,
        ...(updates.personality || {}),
      },
      voice: {
        ...existing.voice,
        ...(updates.voice || {}),
      },
      updated_at: new Date().toISOString(),
    };

    this.personas.set(agentId, updated);
    this.persistToDisk();
    return updated;
  }

  private persistToDisk(): void {
    try {
      const dir = path.dirname(this.storagePath);
      if (!fs.existsSync(dir)) {
        fs.mkdirSync(dir, { recursive: true });
      }
      const data = Array.from(this.personas.values());
      fs.writeFileSync(this.storagePath, JSON.stringify(data, null, 2), 'utf8');
    } catch (err) {
      console.error('[PersonaRegistry] Falha ao persistir personalizações em disco:', err);
    }
  }
}

export const personaRegistry = new PersonaRegistry();
